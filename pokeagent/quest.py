#: Lead at least this far above the leader's strongest mon before walking in.
#: Not a superstition: a leader's ace carries a type advantage and a real
#: moveset, and the loop's own tactics can only pick from what it knows.
LEVEL_MARGIN = 1

#: How much stronger the WHOLE party must get before re-challenging a leader
#: that already beat us. Lead level alone is a bad predictor: this run walked
#: an L53 MIGHTYENA into Wallace three times and lost every one, because the
#: other five sat at 42-49 with nothing super-effective. Each loss also halves
#: the money, which is what drained the run to 62 and stopped all catching.
RETRY_PARTY_GAIN = 8

#: Never walk into a gym below this fraction of max HP.
HEALTHY = 0.85


@dataclass(frozen=True)
class Objective:
    """One concrete thing to do now, with the reason attached."""

    kind: str          # "train" | "travel" | "heal" | "fight_leader" | "done"
    detail: str
    badge: int | None = None
    leader: str | None = None
    map_name: str | None = None
    target_level: int | None = None

    def as_dict(self) -> dict:
        return {
            "kind": self.kind, "detail": self.detail, "badge": self.badge,
            "leader": self.leader, "map": self.map_name,
            "target_level": self.target_level,
        }


class Quest:
    """Turns 'how many badges do I have' into 'what should I do next'."""

    def __init__(self, driver, trainers=None):
        self.d = driver
        self._trainers = trainers
        self.last_reason = ""

    # ---- data ----------------------------------------------------------

    @property
    def trainers(self) -> dict:
        """The generated trainer table, or {} when the guide has not been
        built. Absent data must degrade to 'no level target', never to a
        guess about what a leader brings."""
        if self._trainers is None:
            path = Path(paths.TOOL_DIR) / "docs" / "gen3" / "guide" / "trainers.json"
            try:
                self._trainers = json.loads(path.read_text())
            except Exception as err:  # noqa: BLE001
                log.debug("no trainer table (%s); level targets unavailable", err)
                self._trainers = {}
        return self._trainers

    def leader_party(self, leader: str) -> list[dict]:
        row = self.trainers.get(leader) or {}
        return list(row.get("party") or ())

    def leader_level(self, leader: str) -> int | None:
        party = self.leader_party(leader)
        return max((m["level"] for m in party), default=None) or None

    # ---- state ---------------------------------------------------------

    def badges(self) -> int:
        """How many badges are held.

        `GameState.badges()` returns the NAMES of the badges held, so the
        obvious `int(...)` raises TypeError -- and a bare `except` turned that
        into a permanent 0. The run beat Roxanne, FLAG_BADGE01_GET was set, and
        the loop re-challenged her every step for the rest of the night because
        its own counter said zero. A swallowed exception is worse than a crash.
        """
        try:
            held = self.d.state.badges()
        except Exception as err:  # noqa: BLE001 - no save block on a boot screen
            log.warning("cannot read badges (%s); assuming none", err)
            return 0
        if isinstance(held, int):
            return held
        try:
            return len(held)
        except TypeError:
            log.warning("badges() returned %r; assuming none", held)
            return 0

    def next_gym(self) -> tuple[int, str, str, str] | None:
        """The first gym whose badge we do not hold.

        Keyed on the COUNT rather than on individual badge flags: the count is
        what the save block exposes cheaply, and the spine is ordered, so
        holding n badges means the next gym is the (n+1)th.
        """
        have = self.badges()
        for row in SPINE:
            if row[0] > have:
                return row
        return None

    def party(self) -> list:
        try:
            return [m for m in self.d.state.party() if not m.is_egg]
        except Exception:  # noqa: BLE001
            return []

    def live_cell(self, map_name: str, static_cell: tuple[int, int]
                  ) -> tuple[int, int]:
        """Where that object actually IS, not where the map file puts it.

        Scripts move people at runtime. Norman's map entry puts him at (4,3),
        deep inside a 9x112 gym whose rooms are joined by internal warps; for
        the introduction the game stands him at (4,107), four tiles from the
        door. Walking to the static cell is therefore impossible, and the loop
        spent five minutes failing to reach a man standing next to it.

        The live object list is matched by LOCAL ID -- the map's Nth
        object_event is local id N+1 -- so this is exact rather than
        nearest-neighbour guesswork. Off-map (planning), the static cell is
        all there is and is returned unchanged.
        """
        if self.d.map_name() != map_name:
            return static_cell
        try:
            info = self.d.nav.info(map_name)
            objects = list(getattr(info, "objects", ()) or ())
        except Exception:  # noqa: BLE001
            return static_cell
        local_id = None
        for i, obj in enumerate(objects):
            if (int(obj["x"]), int(obj["y"])) == tuple(static_cell):
                local_id = i + 1
                break
        if local_id is None:
            return static_cell
        try:
            for npc in self.d.live_npcs():
                if npc.get("player"):
                    continue
                if int(npc.get("local_id", -1)) == local_id:
                    return (int(npc["x"]), int(npc["y"]))
        except Exception as err:  # noqa: BLE001
            log.debug("live npc read failed on %s: %s", map_name, err)
        return static_cell

    def leader_cell(self, gym_map: str, leader: str) -> tuple[int, int] | None:
        """Where the leader stands, from the gym map's own object_events.

        Matched on the object's SCRIPT label rather than its graphics id: the
        script is named after the leader
        (`RustboroCity_Gym_EventScript_Roxanne`) while graphics ids are shared,
        and for the double-battle gym there are two sprites to find. Returns
        the first match, so Tate answers for "TateAndLiza" -- talking to
        either one starts the same double battle.
        """
        try:
            info = self.d.nav.info(gym_map)
        except Exception as err:  # noqa: BLE001
            log.debug("no map info for %s: %s", gym_map, err)
            return None
        wanted = [leader.lower()]
        if leader.lower() == "tateandliza":
            wanted = ["tate", "liza"]
        for obj in getattr(info, "objects", ()) or ():
            script = (obj.get("script") or "").lower()
            if any(f"eventscript_{w}" in script for w in wanted):
                return (int(obj["x"]), int(obj["y"]))
        return None

    def lead_level(self) -> int:
        party = self.party()
        return max((m.level for m in party), default=0)

    # ---- the decision --------------------------------------------------

    def pending_story(self) -> StoryStep | None:
        """The first prologue gate still shut, or None.

        Checked before any gym: a party at the right level still cannot reach
        Rustboro while Petalburg's west exit is closed, and the failure looks
        like a pathing bug rather than a story one.

        THE PROLOGUE IS A SEQUENCE, so an unfinished step that is not yet
        offered means the story is BLOCKED -- not that the next one is due.
        This used to `continue` past such a step and hand back something from
        further down the chain, which is how a fresh run at 0 badges was told
        to "walk north into Slateport City" (a boat ride away) and then to
        "battle Wally outside the Mauville gym" (two towns past that). It
        chased each in turn, gave up, and ground Route 115 for an hour with
        the Rustboro gym unvisited.

        Returning None here is what lets the caller fall through to the badge,
        which is usually the very thing that opens the blocked step.
        """
        for step in PROLOGUE:
            try:
                if step.kind == "flag_unset":
                    done = bool(self.d.state.flag(step.name))
                elif step.kind == "var_lt":
                    done = int(self.d.state.var(step.name)) >= int(step.value)
                else:
                    done = True
                if done:
                    continue
                # Incomplete. Actionable only if its own gate is open.
                return step if self._step_offered(step) else None
            except Exception as err:  # noqa: BLE001 - an unreadable save block
                log.debug("cannot evaluate %s: %s", step.name, err)
                return None
        return None

    def _step_offered(self, step) -> bool:
        """Whether a step's `require` gate holds. Unreadable means not offered:
        a step we cannot evaluate is a step we cannot act on either."""
        req = getattr(step, "require", None)
        if not req:
            return True
        try:
            if req.startswith("!"):
                return not self.d.state.flag(req[1:])
            # CAN-USE, not merely own. `field:FLY` asks whether a party member
            # actually knows the move AND the badge that permits it is held --
            # which is what `field_moves()` answers. Owning HM02 is not being
            # able to fly, and gating the collectibles on the ITEM sent the run
            # walking across Hoenn twice.
            if req.startswith("field:"):
                move = req.split(":", 1)[1].upper()
                return self.d.field_moves().get(move) is not None
            if ">=" in req:
                name, n = req.split(">=")
                return int(self.d.state.var(name)) >= int(n)
            return bool(self.d.state.flag(req))
        except Exception as err:  # noqa: BLE001
            log.debug("cannot evaluate require %r: %s", req, err)
            return False

    def _loss_path(self):
        from pathlib import Path

        return Path(str(self.d.state_path) + ".losses.json")

    def _losses(self) -> dict:
        import json

        try:
            return json.loads(self._loss_path().read_text())
        except Exception:  # noqa: BLE001
            return {}

    def party_total(self) -> int:
        return sum(int(m.level or 0) for m in self.party())

    def note_loss(self, leader: str) -> None:
        """Remember how strong we were when this leader beat us."""
        import json

        data = self._losses()
        data[str(leader).upper()] = self.party_total()
        try:
            self._loss_path().write_text(json.dumps(data))
        except Exception:  # noqa: BLE001
            pass

    def retry_bar(self, leader: str):
        """Party total we must exceed before challenging `leader` again."""
        # Case-normalised: the quest tables say "Wallace" while callers and
        # journals say "WALLACE", and a mismatch silently disarms the bar.
        bar = self._losses().get(str(leader).upper())
        return None if bar is None else int(bar) + RETRY_PARTY_GAIN

    def next_objective(self, skip_story: bool = False) -> Objective:
        """What to do right now, and why.

        Ordered so that the reason is always the most specific true one:
        finished > need levels > hurt > not there yet > fight.

        `skip_story` asks the same question WITHOUT the prologue, for a caller
        that has already tried the pending step and found it unreachable. The
        loop used to fall from an abandoned story step straight to training,
        so an unreachable prologue entry hid the gym behind it indefinitely --
        the badge that would have unlocked the step was never attempted.
        """
        story = None if skip_story else self.pending_story()
        if story is not None:
            self.last_reason = f"{story.name} not satisfied"
            return Objective(
                "story", story.detail, map_name=story.map_name,
            )

        gym = self.next_gym()
        if gym is None:
            self.last_reason = "all badges held"
            return Objective("done", "all 8 badges held; the Elite Four is next")

        badge, leader, gym_map, town = gym
        want = self.leader_level(leader)
        have = self.lead_level()

        if want is not None and have < want + LEVEL_MARGIN:
            self.last_reason = (
                f"lead is L{have}; {leader}'s ace is L{want}"
            )
            return Objective(
                "train",
                f"train to L{want + LEVEL_MARGIN} for {leader} "
                f"(ace L{want})",
                badge=badge, leader=leader, map_name=gym_map,
                target_level=want + LEVEL_MARGIN,
            )

        # DO NOT RE-RUN A FIGHT WE HAVE ALREADY LOST AT THIS STRENGTH.
        # Losing halves the money, and the money is what buys the balls the
        # Pokedex needs, so a leader we cannot beat is a drain rather than a
        # gamble. Train until the WHOLE party is materially stronger.
        bar = self.retry_bar(leader)
        total = self.party_total()
        if bar is not None and total < bar:
            self.last_reason = (
                f"{leader} already beat this party (total {total} < {bar})"
            )
            return Objective(
                "train",
                f"train: {leader} beat us at party total {total}; "
                f"need {bar}",
                badge=badge, leader=leader, map_name=gym_map,
                target_level=have + 2,
            )

        party = self.party()
        hurt = [m for m in party if m.max_hp and m.hp / m.max_hp < HEALTHY]
        if hurt:
            who = ", ".join(str(m.nickname) for m in hurt[:3])
            self.last_reason = f"{who} below {HEALTHY:.0%}"
            return Objective(
                "heal", f"heal before {leader} ({who} hurt)",
                badge=badge, leader=leader, map_name=gym_map,
            )

        here = self.d.map_name()
        if here != gym_map:
            self.last_reason = f"at {here}, gym is {gym_map}"
            return Objective(
                "travel", f"go to {gym_map} for badge {badge} ({leader})",
                badge=badge, leader=leader, map_name=gym_map,
            )

        self.last_reason = f"inside {gym_map} at L{have}"
        return Objective(
            "fight_leader", f"beat {leader} for badge {badge}",
            badge=badge, leader=leader, map_name=gym_map,
        )

    # ---- reporting -----------------------------------------------------

    def as_dict(self) -> dict:
        obj = self.next_objective()
        gym = self.next_gym()
        out = {
            "badges": self.badges(),
            "objective": obj.as_dict(),
            "reason": self.last_reason,
        }
        if gym:
            badge, leader, gym_map, town = gym
            out["next_gym"] = {
                "badge": badge, "leader": leader, "map": gym_map,
                "town": town,
                "ace_level": self.leader_level(leader),
                "party": self.leader_party(leader),
            }
        return out

    def summary(self) -> str:
        obj = self.next_objective()
        return f"{self.badges()}/8 badges -- {obj.detail} [{self.last_reason}]"
