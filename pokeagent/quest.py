    choice: str | None = None
    #: The whole box the ROM should be showing, so the label can be resolved
    #: without guessing. SLATEPORT alone sits at position 0 in some
    #: three-option lists and position 1 in others.
    choice_among: tuple[str, ...] | None = None
    #: A cell to STAND ON, for gates that are coord_events rather than
    #: conversations. `talk` walks adjacent and faces, which is exactly wrong
    #: for a trigger you have to step onto.
    stand: tuple[int, int] | None = None
    #: When to OFFER this step at all. The chain is flat but the game is not:
    #: the Go-Goggles exist only after badge 4, the harbor scene only after
    #: Mt. Pyre. Without a gate the first unmet step is offered forever even
    #: when nothing the player can do will meet it. Grammar:
    #:   "FLAG_X"      -- offer while the flag is SET
    #:   "!FLAG_X"     -- offer while the flag is UNSET
    #:   "VAR_X>=n"    -- offer while the var has reached n
    #: None offers unconditionally, as before.
    require: str | None = None


