"""The story spine: what to do next to advance the GAME, not just the party.

An idle loop that only grinds wilds is stuck forever. A real run measured this:
232 battles, level 19, fifteen minutes -- and still 0/8 badges, still on
Route 101. Levels are not progress; badges are.

What is data and what is derived
--------------------------------
The badge ORDER is the one thing the ROM does not state outright: gyms are
independent maps and nothing enumerates them in sequence, so ``SPINE`` below
lists them. Everything else is read:

* the leader's party, levels and types come from the decompilation's own
  trainer data (``docs/guide/trainers.json``, generated by
  ``scripts/build_guide.py`` out of ``src/data/trainer_parties.h``);
* the route to the gym comes from ``MapData.route`` over the real warp graph;
* how many badges we hold comes from the save block.

So this module knows the running order and nothing else. It cannot drift from
the ROM about what is IN a gym.

Tate and Liza share one gym and one badge; listing them separately is an
off-by-one that puts Wallace at badge 9 in a region that has 8.
"""

